@app.post("/predict")
async def predict(
    file: UploadFile = File(...),
    confidence: float = 0.25,
):
    if not 0.01 <= confidence <= 0.99:
        raise HTTPException(
            status_code=400,
            detail="Confidence must be between 0.01 and 0.99.",
        )

    allowed_types = {"image/jpeg", "image/png", "image/webp"}

    if file.content_type not in allowed_types:
        raise HTTPException(
            status_code=415,
            detail="Upload a JPEG, PNG, or WEBP image.",
        )

    # Limit uploads to 10 MB.
    image_bytes = await file.read(10 * 1024 * 1024 + 1)

    if not image_bytes or len(image_bytes) > 10 * 1024 * 1024:
        raise HTTPException(
            status_code=413,
            detail="Image must be non-empty and no larger than 10 MB.",
        )

    try:
        output = predict_image(
            image_bytes,
            confidence=confidence,
        )
        return output

    except Exception as exc:
        # Do not expose internal filesystem paths or tracebacks.
        print(f"Prediction error: {type(exc).__name__}: {exc}")
        raise HTTPException(
            status_code=400,
            detail="Could not process this image.",
        ) from exc


@app.post("/feedback")
def save_feedback(payload: FeedbackRequest):
    """
    Store human-reviewed boxes.

    corrections represents the COMPLETE corrected annotation set
    for the image, including added boxes and excluding false positives.
    An empty list means the reviewer confirms no objects are present.
    """

    image_id = payload.image_id

    # image_id is generated by the server, but still validate it.
    try:
        parsed_id = str(uuid4()) if not image_id else image_id
        if parsed_id != image_id:
            raise ValueError("Invalid ID")
        from uuid import UUID
        UUID(image_id)
    except (ValueError, AttributeError):
        raise HTTPException(
            status_code=400,
            detail="Invalid image_id.",
        )

    image_path = UPLOAD_DIR / f"{image_id}.jpg"

    if not image_path.is_file():
        raise HTTPException(
            status_code=404,
            detail="Original uploaded image not found. Run prediction again.",
        )

    corrections = []

    for detection in payload.corrections:
        if detection.class_id not in CLASS_NAMES:
            raise HTTPException(
                status_code=400,
                detail="Unknown class ID.",
            )

        # Reject boxes that extend beyond the image.
        x1 = detection.x_center - detection.width / 2
        y1 = detection.y_center - detection.height / 2
        x2 = detection.x_center + detection.width / 2
        y2 = detection.y_center + detection.height / 2

        if (
            x1 < 0 or y1 < 0 or x2 > 1 or y2 > 1
        ):
            raise HTTPException(
                status_code=400,
                detail="Bounding box must lie entirely inside the image.",
            )

        corrections.append({
            **detection.model_dump(),
            "label": CLASS_NAMES[detection.class_id],
        })

    feedback_id = str(uuid4())
    correction_json = json.dumps(corrections)

    # Save annotation data as well as its database record.
    # This JSON file is a review record, not yet a training dataset.
    record = {
        "feedback_id": feedback_id,
        "image_id": image_id,
        "image_path": str(image_path),
        "reviewed": True,
        "corrections": corrections,
    }

    feedback_file = FEEDBACK_DIR / f"{feedback_id}.json"
    feedback_file.write_text(
        json.dumps(record, indent=2),
        encoding="utf-8",
    )

    try:
        with get_connection() as connection:
            connection.execute(
                """
                INSERT INTO feedback (
                    feedback_id, image_id, image_path,
                    corrections_json, reviewed
                ) VALUES (?, ?, ?, ?, 1)
                """,
                (
                    feedback_id,
                    image_id,
                    str(image_path),
                    correction_json,
                ),
            )
    except Exception:
        # Avoid leaving an apparently saved record if DB insertion fails.
        feedback_file.unlink(missing_ok=True)
        raise HTTPException(
            status_code=500,
            detail="Could not persist feedback.",
        )

    return {
        "message": "Human corrections saved.",
        "feedback_id": feedback_id,
        "image_id": image_id,
        "correction_count": len(corrections),
        "reviewed": True,
        "model_retrained": False,
    }


@app.get("/feedback/count")
def feedback_count():
    with get_connection() as connection:
        count = connection.execute(
            "SELECT COUNT(*) FROM feedback"
        ).fetchone()[0]

    return {"total_feedback_records": count}


