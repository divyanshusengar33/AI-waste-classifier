def get_connection():
    connection = sqlite3.connect(DB_PATH, timeout=30)
    connection.row_factory = sqlite3.Row
    return connection


def initialize_database():
    with get_connection() as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS feedback (
                feedback_id TEXT PRIMARY KEY,
                image_id TEXT NOT NULL,
                image_path TEXT NOT NULL,
                corrections_json TEXT NOT NULL,
                reviewed INTEGER NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)


initialize_database()


class CorrectedDetection(BaseModel):
    # A class ID from the trained model, 0 through 4.
    class_id: int = Field(ge=0, le=4)

    # Normalized YOLO box: center x, center y, width, height.
    x_center: float = Field(ge=0, le=1)
    y_center: float = Field(ge=0, le=1)
    width: float = Field(gt=0, le=1)
    height: float = Field(gt=0, le=1)


class FeedbackRequest(BaseModel):
    image_id: str = Field(min_length=1, max_length=100)
    corrections: list[CorrectedDetection] = Field(max_length=300)


